export const VIDEO_SCORE_STEP = 10000;

export function crossedVideoMilestone(previousScore: number, score: number): number | null {
  const threshold = Math.floor(score / VIDEO_SCORE_STEP) * VIDEO_SCORE_STEP;
  return threshold > previousScore ? threshold : null;
}

export function zazerkalyeSignalLevel(score: number) {
  return Math.floor((score % VIDEO_SCORE_STEP) / (VIDEO_SCORE_STEP / 5));
}

export function videoRewardForMove({placement, lines, previousScore, score, online}: {
  placement: boolean; lines: number; previousScore: number; score: number; online: boolean;
}): {milestone: number | null} | null {
  if (!online) return null;
  // Comparing the two scores also handles saved games and skipped offline rewards.
  // Several thresholds crossed in one move still produce a single celebration.
  const milestone = crossedVideoMilestone(previousScore, score);
  return (placement && lines >= 4) || milestone !== null ? {milestone} : null;
}

export function pickZazerkalyeVideo(previous: string | null, random: () => number = Math.random): string {
  const candidates = ZAZERKALYE_VIDEO_IDS.filter(id => id !== previous);
  return candidates[Math.floor(random() * candidates.length)];
}

